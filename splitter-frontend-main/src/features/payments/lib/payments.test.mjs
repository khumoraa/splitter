test("every status has an icon AND a text (never colour only), and every event type a text", () => {
  for (const s of STATUSES) { const l = obligationLook(s); assert.ok(l.icon && l.labelKey && l.tone, s); }
  for (const s of ["paid", "partial", "unpaid"]) assert.ok(billLook(s).labelKey);
  assert.equal(billLook("none"), null);
  assert.equal(eventKey("SOMETHING_NEW"), "payments.event.OTHER");
  const lookup = (o, k) => k.split(".").reduce((x, p) => (x == null ? undefined : x[p]), o);
  for (const l of ["en", "ja", "uz"]) {
    const j = JSON.parse(fs.readFileSync(new URL(`../../../shared/config/locales/${l}.json`, import.meta.url), "utf8"));
    const keys = [...STATUSES.map((s) => obligationLook(s).labelKey), ...["paid", "partial", "unpaid"].map((s) => billLook(s).labelKey), ...Object.values(EVENT_KEYS), "payments.event.OTHER", LEGAL_NOTE_KEY];
    for (const k of keys) assert.equal(typeof lookup(j, k), "string", `${l}: ${k}`);
    // the legal note must say it is not a payment or tax document, in every language
    assert.ok(lookup(j, LEGAL_NOTE_KEY).length > 40, `${l}: legal note`);
  }
});

test("statement: escaped, legal note and signature always printed, empty sections dropped", () => {
  const m = {
    title: "Settlement", subtitle: "Cafe <Roma> & Co", shortId: "S-12", generatedAt: "21 Oct 2026",
    sections: [{ title: "Shares", rows: [{ label: "Bob", value: "$5.00" }] }, { title: "Payments", rows: [] }],
    legalNote: "Settlement generated by Splitter for personal record-keeping. Not a payment or tax document.",
    signature: "Splitter",
  };
  const html = statementHtml(m);
  assert.ok(html.includes("Cafe &lt;Roma&gt; &amp; Co"));
  assert.ok(!html.includes("<Roma>"));
  assert.ok(html.includes("Not a payment or tax document."));
  assert.ok(html.includes("Shares") && !html.includes("Payments"));
  assert.ok(!/@[a-z]+\.[a-z]+/.test(html), "no e-mail addresses");
  assert.equal(escapeHtml(`"'`), "&quot;&#39;");
  const txt = statementText(m);
  assert.ok(txt.endsWith("Not a payment or tax document."));
});

test("finance view: rows per currency (never merged), search, periods, progress", () => {
  const u = (id, username) => ({ id, username, uniqueId: `#${1000 + id}`, avatarUrl: null });
  const cur = [
    { currency: "USD", owedToMe: { outstandingMinor: 700, people: [{ id: 1, outstandingMinor: 500, settledMinor: 0, count: 1, user: u(1, "Bob") }, { id: 2, outstandingMinor: 200, settledMinor: 0, count: 1, user: u(2, "Ann") }] }, iOwe: { outstandingMinor: 0, people: [] } },
    { currency: "JPY", owedToMe: { outstandingMinor: 1500, people: [{ id: 1, outstandingMinor: 1500, settledMinor: 0, count: 1, user: u(1, "Bob") }] }, iOwe: { outstandingMinor: 0, people: [] } },
  ];
  const rows = peopleRows(cur, "owedToMe", "");
  assert.deepEqual(rows.map((r) => r.key), ["JPY:1", "USD:1", "USD:2"], "Bob appears once per currency");
  assert.deepEqual(peopleRows(cur, "owedToMe", "an").map((r) => r.key), ["USD:2"]);
  assert.deepEqual(peopleRows(cur, "owedToMe", "#1001").map((r) => r.key), ["JPY:1", "USD:1"]);
  assert.deepEqual(peopleRows(cur, "iOwe", ""), []);
  const now = Date.parse("2026-10-21T00:00:00Z");
  assert.equal(periodFrom("all", now), null);
  assert.equal(periodFrom("30d", now), "2026-09-21T00:00:00.000Z");
  assert.equal(settledRatio(5, 10), 0.5);
  assert.equal(settledRatio(0, 0), 1);
  assert.equal(settledRatio(15, 10), 1);
});
