import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import * as client from "./rules.ts";
import * as server from "../../../../../splitter-backend-main/src/utils/obligationLogic.ts";
import { obligationLook, billLook, eventKey, EVENT_KEYS } from "./status-ui.ts";
import { statementHtml, statementText, escapeHtml, LEGAL_NOTE_KEY } from "./statement.ts";
import { peopleRows, periodFrom, settledRatio } from "./finance-view.ts";

const STATUSES = ["UNPAID", "PARTIALLY_PAID", "PAID_PENDING_CONFIRMATION", "PAID", "FORGIVEN", "CANCELLED"];
const ROLES = ["debtor", "creditor", "participant", "outsider"];
const ACTIONS = ["markPaid", "recordReceived", "confirm", "reject", "forgive", "remind"];

test("client rules match the server rules on every combination", () => {
  const amounts = [[1000, 0, 0], [1000, 400, 0], [1000, 400, 600], [1000, 1000, 0], [333, 0, 333], [1, 0, 0]];
  for (const [amountMinor, confirmedMinor, pendingMinor] of amounts) {
    const a = { amountMinor, confirmedMinor, pendingMinor };
    assert.equal(client.recordableMinor(a), server.recordableMinor(a));
    for (const s of STATUSES) {
      assert.equal(client.deriveStatus(a, s), server.deriveStatus(a, s));
      assert.equal(client.outstandingMinor(a, s), server.outstandingMinor(a, s));
      for (const amt of [undefined, 0, 1, 399, 400, 600, 601, 1.5]) assert.deepEqual(client.checkAmount(a, s, amt), server.checkPayment(a, s, amt), `${s} ${amt}`);
    }
  }
  for (const r of ROLES) for (const x of ACTIONS) assert.equal(client.can(r, x), server.can(r, x), `${r} ${x}`);
});

test("buttons by role and status", () => {
  const open = { amountMinor: 1000, confirmedMinor: 0, pendingMinor: 0 };
  assert.deepEqual(client.allowedActions("debtor", "UNPAID", false, open), ["markPaid"]);
  assert.deepEqual(client.allowedActions("creditor", "UNPAID", false, open), ["recordReceived", "forgive", "remind"]);
  assert.deepEqual(client.allowedActions("creditor", "PAID_PENDING_CONFIRMATION", true, { amountMinor: 1000, confirmedMinor: 0, pendingMinor: 1000 }), ["confirm", "reject", "forgive", "remind"]);
  assert.deepEqual(client.allowedActions("debtor", "PAID_PENDING_CONFIRMATION", true, { amountMinor: 1000, confirmedMinor: 0, pendingMinor: 1000 }), [], "nothing left to mark");
  assert.deepEqual(client.allowedActions("debtor", "PAID_PENDING_CONFIRMATION", true, { amountMinor: 1000, confirmedMinor: 0, pendingMinor: 400 }), ["markPaid"]);
  assert.deepEqual(client.allowedActions("participant", "UNPAID", false, open), []);
  assert.deepEqual(client.allowedActions("outsider", "UNPAID", false, open), []);
  for (const s of ["PAID", "FORGIVEN", "CANCELLED"]) for (const r of ROLES) assert.deepEqual(client.allowedActions(r, s, false, open), []);
});

