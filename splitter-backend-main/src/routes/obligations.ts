/**
 * @swagger
 * /obligations/session/{sessionId}/statement:
 *   get:
 *     summary: Data for a neutral settlement statement of one bill (no e-mails; carries the legal note)
 *     tags: [Payments]
 *     security:
 *       - bearerAuth: []
 * /obligations/people/{uniqueId}/statement:
 *   get:
 *     summary: Data for a settlement statement between me and one person (optional from, to, currency)
 *     tags: [Payments]
 *     security:
 *       - bearerAuth: []
 */
router.get("/session/:sessionId/statement", async (req: AuthRequest, res: Response) => {
  try {
    const sid = idParam(req.params.sessionId);
    if (!sid) return fail(res, "VALIDATION", { field: "sessionId" });
    if (!(await canViewSession(sid, req.user!.id))) return fail(res, "NOT_FOUND");
    const ledger = await sessionLedger(sid, req.user!.id);
    const entry = await prisma.sessionHistoryEntry.findUnique({ where: { sessionId: sid }, select: { payload: true, currency: true } });
    const payload = (entry?.payload ?? {}) as { totals?: { byItem?: { name: string; total: number; kind?: string }[]; byParticipant?: { uniqueId: string; username: string; amountOwed: number; amountMinor?: number }[]; minorPerUnit?: number } };
    const per = payload.totals?.minorPerUnit ?? (fractionDigits(entry?.currency) === 0 ? 1 : 100);
    const toMinor = (v: number) => Math.round(Number((Number(v) * per).toPrecision(12)));
    return res.json({
      kind: "bill",
      statementId: `S-${sid}`,
      generatedAt: new Date().toISOString(),
      legalNote: LEGAL_NOTE,
      bill: ledger.session,
      currency: ledger.totals.currency ?? entry?.currency ?? null,
      items: (payload.totals?.byItem ?? []).map((i) => ({ name: i.name, kind: i.kind ?? null, totalMinor: toMinor(i.total) })),
      shares: (payload.totals?.byParticipant ?? []).map((p) => ({ uniqueId: p.uniqueId, username: p.username, amountMinor: p.amountMinor ?? toMinor(p.amountOwed) })),
      obligations: ledger.obligations.map((o) => ({ id: o.id, debtor: o.debtor, creditor: o.creditor, amountMinor: o.amountMinor, settledMinor: o.confirmedMinor, pendingMinor: o.pendingMinor, outstandingMinor: o.outstandingMinor, status: o.status, payments: o.payments })),
      events: ledger.events,
      totals: ledger.totals,
    });
  } catch (e) {
    return handle(res, e, "GET /obligations/session/:id/statement");
  }
});

router.get("/people/:uniqueId/statement", async (req: AuthRequest, res: Response) => {
  try {
    const me = req.user!.id;
    const other = await prisma.user.findUnique({ where: { uniqueId: String(req.params.uniqueId).trim() }, select: PUBLIC_USER_SELECT });
    if (!other || other.id === me) return fail(res, "NOT_FOUND");
    const base = filtersFrom({ ...req.query, status: undefined, role: undefined }, me);
    if ("error" in base) return fail(res, "VALIDATION", { field: base.error });
    const pair: Prisma.ObligationWhereInput = { OR: [{ debtorId: me, creditorId: other.id }, { creditorId: me, debtorId: other.id }] };
    const rows = await prisma.obligation.findMany({ where: { AND: [base, pair] }, include: LIST_INCLUDE, orderBy: [{ createdAt: "asc" }, { id: "asc" }] });
    if (rows.length === 0) return fail(res, "NOT_FOUND");
    const meUser = await prisma.user.findUnique({ where: { id: me }, select: PUBLIC_USER_SELECT });
    return res.json({
      kind: "person",
      statementId: `P-${Math.min(me, other.id)}-${Math.max(me, other.id)}`,
      generatedAt: new Date().toISOString(),
      legalNote: LEGAL_NOTE,
      me: meUser,
      person: other,
      currencies: await summaryFor(me, { AND: [base, pair] }),
      lines: rows.map((o) => listView(o, me)),
    });
  } catch (e) {
    return handle(res, e, "GET /obligations/people/:uniqueId/statement");
  }
});

