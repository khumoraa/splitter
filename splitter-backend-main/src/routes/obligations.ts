/** The note every statement and export carries (the client shows it translated). */
export const LEGAL_NOTE = "Settlement generated by Splitter for personal record-keeping. Not a payment or tax document.";

const handle = (res: Response, e: unknown, where: string) => {
  if (e instanceof PaymentError) return fail(res, e.code as ErrorCode, e.extra);
  console.error(`${where} error:`, e);
  return serverError(res);
};
const idParam = (v: unknown) => { const n = Number(v); return isDbId(n) ? n : null; };

// ---------------------------------------------------------------- filters shared by list / summary / person

const STATUSES: ObligationStatus[] = ["UNPAID", "PARTIALLY_PAID", "PAID_PENDING_CONFIRMATION", "PAID", "FORGIVEN", "CANCELLED"];

function filtersFrom(q: Record<string, unknown>, me: number): Prisma.ObligationWhereInput | { error: string } {
  const where: Prisma.ObligationWhereInput[] = [{ OR: [{ debtorId: me }, { creditorId: me }] }, { status: { not: "CANCELLED" } }];
  if (q.status !== undefined) {
    const raw = String(q.status);
    const list = raw === "open" ? ["UNPAID", "PARTIALLY_PAID", "PAID_PENDING_CONFIRMATION"] : raw === "settled" ? ["PAID", "FORGIVEN"] : raw.split(",");
    if (!list.every((s) => (STATUSES as string[]).includes(s))) return { error: "status" };
    where.push({ status: { in: list as ObligationStatus[] } });
  }
  for (const [key, op] of [["from", "gte"], ["to", "lte"]] as const) {
    if (q[key] !== undefined) {
      const d = new Date(String(q[key]));
      if (Number.isNaN(d.getTime())) return { error: key };
      where.push({ createdAt: { [op]: d } });
    }
  }
  if (q.groupId !== undefined) {
    const g = idParam(q.groupId);
    if (!g) return { error: "groupId" };
    where.push({ session: { groupId: g } });
  }
  if (q.currency !== undefined) {
    const c = String(q.currency).toUpperCase();
    if (!/^[A-Z]{3}$/.test(c) && c !== "UNKNOWN") return { error: "currency" };
    where.push({ currency: c });
  }
  if (q.role === "creditor") where.push({ creditorId: me });
  else if (q.role === "debtor") where.push({ debtorId: me });
  else if (q.role !== undefined) return { error: "role" };
  return { AND: where };
}

async function personFilter(uniqueId: unknown, me: number): Promise<Prisma.ObligationWhereInput | null> {
  if (typeof uniqueId !== "string" || !uniqueId.trim()) return null;
  const u = await prisma.user.findUnique({ where: { uniqueId: uniqueId.trim() }, select: { id: true } });
  if (!u) return { id: -1 }; // nobody: empty result
  return { OR: [{ debtorId: me, creditorId: u.id }, { creditorId: me, debtorId: u.id }] };
}

const LIST_INCLUDE = {
  ...OBLIGATION_INCLUDE,
  session: { select: { id: true, createdAt: true, group: { select: { id: true, name: true } }, historyEntry: { select: { sessionName: true, finalizedAt: true } } } },
} satisfies Prisma.ObligationInclude;

type ListRow = Prisma.ObligationGetPayload<{ include: typeof LIST_INCLUDE }>;
const listView = (o: ListRow, me: number) => ({
  ...obligationView(o, me),
  bill: { id: o.session.id, name: o.session.historyEntry?.sessionName ?? null, date: o.session.historyEntry?.finalizedAt ?? o.session.createdAt, group: o.session.group },
});

