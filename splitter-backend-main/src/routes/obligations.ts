/**
 * @swagger
 * /obligations:
 *   get:
 *     summary: My debts in both directions with filters status (list, open or settled), from, to, groupId, currency, role (creditor or debtor), person (uniqueId)
 *     tags: [Payments]
 *     security:
 *       - bearerAuth: []
 * /obligations/summary:
 *   get:
 *     summary: Owed to me and I owe, per currency (never mixed) and per person; same filters
 *     tags: [Payments]
 *     security:
 *       - bearerAuth: []
 */
router.get("/", async (req: AuthRequest, res: Response) => {
  try {
    const me = req.user!.id;
    const where = filtersFrom(req.query, me);
    if ("error" in where) return fail(res, "VALIDATION", { field: where.error });
    const person = await personFilter(req.query.person, me);
    const rows = await prisma.obligation.findMany({ where: person ? { AND: [where, person] } : where, include: LIST_INCLUDE, orderBy: [{ createdAt: "desc" }, { id: "desc" }], take: 300 });
    return res.json({ obligations: rows.map((o) => listView(o, me)) });
  } catch (e) {
    return handle(res, e, "GET /obligations");
  }
});

async function summaryFor(me: number, where: Prisma.ObligationWhereInput) {
  const rows = await prisma.obligation.findMany({
    where,
    select: { currency: true, debtorId: true, creditorId: true, amountMinor: true, confirmedMinor: true, status: true },
  });
  const summaryRows: SummaryRow[] = rows.map((r) => ({
    currency: r.currency,
    direction: r.creditorId === me ? "owedToMe" : "iOwe",
    counterpartId: r.creditorId === me ? r.debtorId : r.creditorId,
    amountMinor: r.amountMinor,
    confirmedMinor: r.confirmedMinor,
    status: r.status as ObligationStatus,
  }));
  const currencies = summarize(summaryRows);
  const ids = [...new Set(summaryRows.map((r) => r.counterpartId))];
  const people = await prisma.user.findMany({ where: { id: { in: ids } }, select: PUBLIC_USER_SELECT });
  const byId = new Map(people.map((p) => [p.id, { ...p, avatarUrl: p.avatarUrl ?? null }]));
  return currencies.map((c) => ({
    ...c,
    minorPerUnit: fractionDigits(c.currency) === 0 ? 1 : 100,
    owedToMe: { ...c.owedToMe, people: c.owedToMe.people.map((p) => ({ ...p, user: byId.get(p.id) ?? null })) },
    iOwe: { ...c.iOwe, people: c.iOwe.people.map((p) => ({ ...p, user: byId.get(p.id) ?? null })) },
  }));
}

router.get("/summary", async (req: AuthRequest, res: Response) => {
  try {
    const me = req.user!.id;
    const where = filtersFrom(req.query, me);
    if ("error" in where) return fail(res, "VALIDATION", { field: where.error });
    const person = await personFilter(req.query.person, me);
    const currencies = await summaryFor(me, person ? { AND: [where, person] } : where);

    // settlement progress per group (only groups I am in a debt with), per currency
    const groupRows = await prisma.obligation.findMany({
      where: { AND: [where, { session: { groupId: { not: null } } }] },
      select: { currency: true, amountMinor: true, confirmedMinor: true, status: true, session: { select: { group: { select: { id: true, name: true } } } } },
    });
    const groups = new Map<string, { group: { id: number; name: string }; currency: string; totalMinor: number; settledMinor: number }>();
    for (const r of groupRows) {
      const g = r.session.group!;
      const key = `${g.id}:${r.currency}`;
      const e = groups.get(key) ?? { group: g, currency: r.currency, totalMinor: 0, settledMinor: 0 };
      e.totalMinor += r.amountMinor;
      e.settledMinor += r.status === "FORGIVEN" ? r.amountMinor : r.confirmedMinor;
      groups.set(key, e);
    }
    return res.json({ currencies, groups: [...groups.values()] });
  } catch (e) {
    return handle(res, e, "GET /obligations/summary");
  }
});

/**
 * @swagger
 * /obligations/people/{uniqueId}:
 *   get:
 *     summary: Everything between me and one person - balance per currency, bills, payments
 *     tags: [Payments]
 *     security:
 *       - bearerAuth: []
 */
router.get("/people/:uniqueId", async (req: AuthRequest, res: Response) => {
  try {
    const me = req.user!.id;
    const other = await prisma.user.findUnique({ where: { uniqueId: String(req.params.uniqueId).trim() }, select: PUBLIC_USER_SELECT });
    if (!other || other.id === me) return fail(res, "NOT_FOUND");
    const where: Prisma.ObligationWhereInput = { status: { not: "CANCELLED" }, OR: [{ debtorId: me, creditorId: other.id }, { creditorId: me, debtorId: other.id }] };
    const [rows, currencies] = await Promise.all([
      prisma.obligation.findMany({ where, include: LIST_INCLUDE, orderBy: [{ createdAt: "desc" }, { id: "desc" }] }),
      summaryFor(me, where),
    ]);
    if (rows.length === 0) return fail(res, "NOT_FOUND"); // no shared bills: nothing to show (and nothing to learn)
    return res.json({ person: { ...other, avatarUrl: other.avatarUrl ?? null }, currencies, obligations: rows.map((o) => listView(o, me)) });
  } catch (e) {
    return handle(res, e, "GET /obligations/people/:uniqueId");
  }
});

