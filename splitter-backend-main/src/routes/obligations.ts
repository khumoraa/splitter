/**
 * @swagger
 * tags:
 *   name: Payments
 *   description: Records of debts and of settlements made OUTSIDE the app (Splitter never moves money)
 * /obligations/session/{sessionId}:
 *   get:
 *     summary: Debts, payments, the event log and totals of one bill (participants only)
 *     tags: [Payments]
 *     security:
 *       - bearerAuth: []
 */
router.get("/session/:sessionId", async (req: AuthRequest, res: Response) => {
  try {
    const sid = idParam(req.params.sessionId);
    if (!sid) return fail(res, "VALIDATION", { field: "sessionId" });
    if (!(await canViewSession(sid, req.user!.id))) return fail(res, "NOT_FOUND");
    return res.json(await sessionLedger(sid, req.user!.id));
  } catch (e) {
    return handle(res, e, "GET /obligations/session/:id");
  }
});

/**
 * @swagger
 * /obligations/{id}/payments:
 *   post:
 *     summary: The debtor marks "I paid" (awaits confirmation) or the creditor records "Received" (confirmed). Body amountMinor (optional, default the rest), method CASH, TRANSFER or OTHER, note. Header Idempotency-Key
 *     tags: [Payments]
 *     security:
 *       - bearerAuth: []
 */
router.post("/:id/payments", writeLimit, async (req: AuthRequest, res: Response) => {
  try {
    const id = idParam(req.params.id);
    if (!id) return fail(res, "VALIDATION", { field: "id" });
    const r = await recordPayment({
      obligationId: id, userId: req.user!.id, amountMinor: req.body?.amountMinor, method: req.body?.method, note: req.body?.note,
      idemKey: req.header("idempotency-key") ?? undefined,
    });
    return res.json({ payment: { id: r.payment.id, status: r.payment.status, amountMinor: r.payment.amountMinor }, replayed: r.replayed });
  } catch (e) {
    return handle(res, e, "POST /obligations/:id/payments");
  }
});

/**
 * @swagger
 * /obligations/{id}/payments/{paymentId}/confirm:
 *   post:
 *     summary: The creditor confirms a pending mark
 *     tags: [Payments]
 *     security:
 *       - bearerAuth: []
 * /obligations/{id}/payments/{paymentId}/reject:
 *   post:
 *     summary: The creditor rejects a pending mark; body reason (required)
 *     tags: [Payments]
 *     security:
 *       - bearerAuth: []
 */
for (const confirm of [true, false]) {
  router.post(`/:id/payments/:paymentId/${confirm ? "confirm" : "reject"}`, writeLimit, async (req: AuthRequest, res: Response) => {
    try {
      const id = idParam(req.params.id);
      const pid = idParam(req.params.paymentId);
      if (!id || !pid) return fail(res, "VALIDATION", { field: "id" });
      return res.json(await resolvePayment({ obligationId: id, paymentId: pid, userId: req.user!.id, confirm, reason: req.body?.reason }));
    } catch (e) {
      return handle(res, e, `POST /obligations/:id/payments/:pid/${confirm ? "confirm" : "reject"}`);
    }
  });
}

